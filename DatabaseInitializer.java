package com.college.smartparking;
import org.springframework.boot.CommandLineRunner;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

@Component
public class DatabaseInitializer implements CommandLineRunner {
    private final JdbcTemplate jdbc;
    public DatabaseInitializer(JdbcTemplate jdbc) { this.jdbc = jdbc; }

    @Override
    public void run(String... args) {
        jdbc.execute("CREATE TABLE IF NOT EXISTS parking_slots (" +
                "slot_id INTEGER PRIMARY KEY, location VARCHAR(80) NOT NULL, slot_type VARCHAR(30) NOT NULL, " +
                "status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE' CHECK (status IN ('AVAILABLE','OCCUPIED')), " +
                "vehicle_no VARCHAR(40), booked_at VARCHAR(30))");
        jdbc.execute("CREATE TABLE IF NOT EXISTS parking_log (" +
                "log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, slot_id INTEGER NOT NULL, " +
                "vehicle_no VARCHAR(40) NOT NULL, action VARCHAR(20) NOT NULL, event_time VARCHAR(30) NOT NULL)");
        Integer count = jdbc.queryForObject("SELECT COUNT(*) FROM parking_slots", Integer.class);
        if (count != null && count == 0) {
            String[] types = {"CAR", "CAR", "CAR", "EV", "TWO-WHEELER",
                    "TWO-WHEELER", "CAR", "EV", "CAR", "TWO-WHEELER"};
            for (int i = 1; i <= types.length; i++) {
                jdbc.update("INSERT INTO parking_slots(slot_id, location, slot_type) VALUES (?, ?, ?)",
                        i, "Zone " + ((i - 1) / 5 + 1), types[i - 1]);
            }
        }
    }
}
